"""
Generates the adaptive launcher icon (vector drawables) for Gym Trainer.

Adaptive icons are 108x108 with a 66-unit safe zone (radius 33 around 54,54); launchers
crop the rest to their own shape. Everything important stays within radius ~31.

Usage: python -I tools/gen_icon.py
"""
import os

RES = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'app', 'src', 'main', 'res', 'drawable')


def rrect(x, y, w, h, r):
    r = min(r, w / 2, h / 2)
    return (f"M{x + r:.2f},{y:.2f}h{w - 2 * r:.2f}a{r:.2f},{r:.2f} 0 0 1 {r:.2f},{r:.2f}"
            f"v{h - 2 * r:.2f}a{r:.2f},{r:.2f} 0 0 1 {-r:.2f},{r:.2f}"
            f"h{-(w - 2 * r):.2f}a{r:.2f},{r:.2f} 0 0 1 {-r:.2f},{-r:.2f}"
            f"v{-(h - 2 * r):.2f}a{r:.2f},{r:.2f} 0 0 1 {r:.2f},{-r:.2f}z")


def circle(cx, cy, r):
    return f"M{cx - r:.2f},{cy:.2f}a{r:.2f},{r:.2f} 0 1 0 {2 * r:.2f},0a{r:.2f},{r:.2f} 0 1 0 {-2 * r:.2f},0z"


# Dumbbell, horizontal and centred on (54,54); rotated as a group.
HANDLE = rrect(42, 51, 24, 6, 3)
INNER = [rrect(35.5, 37.5, 7.5, 33, 3.2), rrect(65, 37.5, 7.5, 33, 3.2)]
OUTER = [rrect(29, 43, 6, 22, 3), rrect(73, 43, 6, 22, 3)]
CAPS = [rrect(26, 50.5, 3.5, 7, 1.5), rrect(78.5, 50.5, 3.5, 7, 1.5)]

WHITE, ORANGE = "#FFFFFF", "#FF8A3D"

HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n'
          '<!-- Generated by tools/gen_icon.py. -->\n'
          '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
          '    xmlns:aapt="http://schemas.android.com/aapt"\n'
          '    android:width="108dp" android:height="108dp"\n'
          '    android:viewportWidth="108" android:viewportHeight="108">\n')


def path(d, color, alpha=None):
    a = f' android:fillAlpha="{alpha}"' if alpha is not None else ''
    return f'    <path android:fillColor="{color}"{a} android:pathData="{d}" />\n'


def ring(r_out, r_in):
    # Even-odd ring: outer circle minus inner circle.
    return (f'    <path android:fillColor="#FFFFFF" android:fillAlpha="0.22" android:fillType="evenOdd"\n'
            f'        android:pathData="{circle(54, 54, r_out)} {circle(54, 54, r_in)}" />\n')


def dumbbell(main, accent):
    s = '    <group android:rotation="-38" android:scaleX="0.88" android:scaleY="0.88" android:pivotX="54" android:pivotY="54">\n'
    s += path(HANDLE, main)
    for p in CAPS:
        s += path(p, main)
    for p in OUTER:
        s += path(p, main)
    for p in INNER:
        s += path(p, accent)
    s += '    </group>\n'
    return s


background = HEADER + '''    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="108" android:endY="108">
                <item android:offset="0" android:color="#FF3D7BFF" />
                <item android:offset="0.55" android:color="#FF5B5BF5" />
                <item android:offset="1" android:color="#FF7A3FE0" />
            </gradient>
        </aapt:attr>
    </path>
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="30" android:centerY="24" android:gradientRadius="70">
                <item android:offset="0" android:color="#40FFFFFF" />
                <item android:offset="1" android:color="#00FFFFFF" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
'''

# Soft drop shadow under the dumbbell, then the dumbbell itself.
shadow = '    <group android:translateX="1.2" android:translateY="2.2">\n' + \
    dumbbell("#1A1040", "#1A1040").replace('android:fillColor="#1A1040"', 'android:fillColor="#1A1040" android:fillAlpha="0.28"') + \
    '    </group>\n'
foreground = HEADER + ring(31, 28.6) + shadow + dumbbell(WHITE, ORANGE) + '</vector>\n'

# Android 13+ themed icons: one flat shape, the system picks the colours.
monochrome = HEADER + dumbbell("#000000", "#000000") + '</vector>\n'

for name, body in [('ic_launcher_background', background), ('ic_launcher_foreground', foreground),
                   ('ic_launcher_monochrome', monochrome)]:
    with open(os.path.join(RES, name + '.xml'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(body)
print('icon drawables written')
