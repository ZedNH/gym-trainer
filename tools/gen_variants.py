def slug(s):
    return re.sub(r'[^A-Za-z0-9]+', '_', s).strip('_')


def tokens(s):
    s = s.lower().replace('-', ' ').replace("'", '')
    s = s.replace('dumbbells', 'dumbbell').replace('bands', 'band').replace('flyes', 'fly').replace('flye', 'fly')
    s = s.replace('raises', 'raise').replace('curls', 'curl').replace('rows', 'row').replace('lunges', 'lunge')
    s = s.replace('squats', 'squat').replace('extensions', 'extension').replace('pushdowns', 'pushdown')
    s = s.replace('step ups', 'step up').replace('stepup', 'step up').replace('deadlifts', 'deadlift')
    return set(w for w in re.findall(r'[a-z0-9]+', s) if w not in {'with', 'the', 'a', 'on', 'to', 'machine', 'attachment'})


EQ_TOKENS = {"Band": {"band"}, "Barbell": {"barbell"}, "Cable": {"cable"}, "Dumbbell": {"dumbbell"},
             "Kettlebell": {"kettlebell"}, "Machine": set(), "Smith Machine": {"smith"}, "Bodyweight": set(), "Plate": {"plate"}}


HARMLESS = {'full', 'standing', 'medium', 'grip', 'barbell', 'dumbbell', 'band', 'cable', 'kettlebell', 'smith', 'leverage', 'raise'}


def main(path):
    data = json.load(open(path, encoding='utf-8'))
    by_id = {x['id']: x for x in data}
    existing = [(tokens(x['name']), x['equipment'], x['name']) for x in data]
    out, skipped, noimg = [], [], []
    used = set()
    for m in MOVES:
        base_tok = tokens(m['base'])
        for eq, cands in m['eqs'].items():
            name = m['base'] if eq == 'Bodyweight' else f"{m['base']} - {eq}"
            app_eq = APP_EQUIPMENT.get(eq, eq)
            want = base_tok | EQ_TOKENS[eq]
            dup = next((n for t, e, n in existing if want <= t and (t - want) <= HARMLESS and
                        (e == app_eq or EQ_TOKENS[eq] & t or (eq == 'Bodyweight' and e in ('Bodyweight', 'Other')))), None)
            if not dup:
                dup = next((x['name'] for x in data if x['name'].lower() == name.lower()), None)
            if dup:
                skipped.append(f"{name}  ~ {dup}")
                continue
            src = next((c for c in cands if c in by_id and by_id[c]['images'] > 0), None)
            if src is None:
                noimg.append(name)
            vid = 'v_' + slug(name)
            if vid in used:
                continue
            used.add(vid)
            timed = m['secs'] > 0
            out.append({
                'id': vid, 'name': name, 'group': m['group'], 'primary': m['primary'], 'secondary': m['secondary'],
                'equipment': app_eq, 'level': m['level'], 'pattern': m['pattern'], 'compound': m['compound'],
                'category': 'strength', 'setup': SETUP[eq], 'steps': m['steps'], 'mistakes': m['mistakes'],
                'repMin': m['reps'][0], 'repMax': m['reps'][1], 'rest': m['reps'][2], 'timed': timed, 'seconds': m['secs'],
                'images': by_id[src]['images'] if src else 0, 'imageOf': src or '', 'featured': False,
            })
    dest = path.replace('exercises.json', 'exercises_variants.json')
    with open(dest, 'w', encoding='utf-8') as f:
        json.dump(out, f, ensure_ascii=False, indent=0)
    print(f"variants written: {len(out)}  skipped (already in library): {len(skipped)}  without photo: {len(noimg)}")
    print("no photo:", noimg)
    print("skipped:"); [print("  ", x) for x in skipped]


if __name__ == '__main__':
    main(sys.argv[1])
